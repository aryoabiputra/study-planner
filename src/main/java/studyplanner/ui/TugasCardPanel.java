    public void setData(Tugas tugas, String namaMatkul) {
        this.tugas = tugas;

        // Judul tugas di checkbox
        jCheckBox1.setText(tugas.getJudul());

        // Info ringkas di text field
        String infoMatkul = (namaMatkul == null || namaMatkul.isBlank())
                ? "Tanpa mata kuliah"
                : namaMatkul;

        String info = infoMatkul
                + "  •  " + tugas.getTipe()
                + "  •  Prioritas " + tugas.getPrioritas()
                + "  •  " + tugas.getStatus();

        jTextField1.setText(info);

        // Deadline
        tglLabel.setText(tugas.getDeadline());
    }

