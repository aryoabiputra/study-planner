    private void tombolSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombolSimpanActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelDaftarMatkul.getModel();

        String dosen = inputDosen.getText();
        String matkul = inputMatkul.getText();
        String sks = inputSKS.getSelectedItem().toString();
        String hari = inputHari.getSelectedItem().toString();

        if (dosen.isEmpty() || matkul.isEmpty() || sks.equals("--") || hari.equals("---")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Harap lengkapi semua data!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        model.addRow(new Object[]{dosen, matkul, hari, sks});

        inputDosen.setText("");
        inputMatkul.setText("");
        inputSKS.setSelectedIndex(0); 
        inputHari.setSelectedIndex(0);
    }//GEN-LAST:event_tombolSimpanActionPerformed

